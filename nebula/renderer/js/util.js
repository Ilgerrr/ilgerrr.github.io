export function escapeHtml(s) {
  return String(s).replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
}

export function relTime(ms) {
  const d = (Date.now() - ms) / 1000;
  if (d < 60) return 'zojuist';
  if (d < 3600) return Math.floor(d / 60) + ' min geleden';
  if (d < 86400) return Math.floor(d / 3600) + ' u geleden';
  if (d < 86400 * 2) return 'gisteren';
  if (d < 86400 * 30) return Math.floor(d / 86400) + ' dagen geleden';
  return new Date(ms).toLocaleDateString('nl-NL', { day: 'numeric', month: 'short', year: 'numeric' });
}
